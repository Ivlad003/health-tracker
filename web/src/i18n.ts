export type Key = keyof typeof UK;

export function t(lang: Lang, key: Key): string {
  return (lang === "uk" ? UK : EN)[key];
}

export function locale(lang: Lang): string {
  return lang === "uk" ? "uk-UA" : "en-US";
}

export function formatNumber(lang: Lang, value: number | string | null | undefined): string {
  const n = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(n)) return "—";
  return Math.round(n).toLocaleString(locale(lang));
}
